library lifex_ai.features.women_health.women_ashram_care_copy;

class WomenAshramCareCopy {
  const WomenAshramCareCopy._();

  static String weekly(int week) {
    final w = week.clamp(1, 40);
    if (w <= 13) {
      return 'الأسبوع $w من 40. هدوء، نوم كافٍ، وحمض فوليك إن وصفته الطبيبة. '
          'تجنّبي الإجهاد الثقيل والمواد الضارة. هذه توعية عامة.';
    }
    if (w <= 27) {
      return 'الأسبوع $w من 40. حركة خفيفة إن سمحت الطبيبة، غذاء متنوّع، وماء. '
          'راقبي جسمك بلطف. ليست نتيجة سونار.';
    }
    return 'الأسبوع $w من 40. استعداد هادئ، راحة، ومتابعة الحركة كما تعلّمكِ الطبيبة. '
        'جهّزي أسئلة الموعد. التطبيق لا يدير الولادة.';
  }

  static String daily(int weekday) {
    switch (weekday) {
      case DateTime.monday:
        return 'اليوم: لا تُجهدي جسمك فوق طاقته. اجلسي واشربي ماءً على مهل.';
      case DateTime.tuesday:
        return 'اليوم: طعام بسيط ناضج، وابتعدي عما لم توافقي عليه مع الطبيبة.';
      case DateTime.wednesday:
        return 'اليوم: نوم مبكر إن أمكن. الراحة تخدمكِ ومن تعتنين به.';
      case DateTime.thursday:
        return 'اليوم: إن كان عملُكِ شاقاً، اطلبي فترات هدوء. لا بطولة على حسابك.';
      case DateTime.friday:
        return 'اليوم: شراب كافٍ، وملح بإذن الطبيبة إن لزم. لا حميات صارمة من عندك.';
      case DateTime.saturday:
        return 'اليوم: العلاقة الزوجية بلطف واحترام لراحتكِ فقط إن سمحت الطبيبة، وإلا فالراحة أولى.';
      default:
        return 'اليوم: يوم هدوء. رسالة خاصة لكِ، ليست للإعلان أمام أحد.';
    }
  }
}
